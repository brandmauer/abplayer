    /** "ru" | "en". Состояние Compose — смена языка перерисовывает интерфейс. */
    var lang by mutableStateOf("ru")

    /** Настройка приложения: "" — как в системе, "ru" или "en". */
    fun resolve(setting: String): String = when (setting) {
        "ru", "en" -> setting
        else -> if (Locale.getDefault().language == "ru") "ru" else "en"
    }

    fun t(s: String): String {
        if (s.isEmpty()) return s
        if (lang != "en") return s
        dict[s]?.let { return it }
        for ((re, f) in patterns) {
            val m = re.matchEntire(s) ?: continue
            return f(m)
        }
        return s
    }

    private fun plural(n: Int, one: String, many: String) = if (n == 1) one else many

    private fun p(re: String, f: (MatchResult) -> String): Pair<Regex, (MatchResult) -> String> = Regex(re) to f

