 *
 * Исходные тексты в коде — русские. Перевод на английский подставляется на самом нижнем уровне
 * (композабл Txt и уведомления Hub), поэтому язык переключается сразу во всём приложении:
 * точные строки берутся из словаря, строки с числами/названиями — по шаблонам ниже.
 * Пользовательские данные (названия треков, плейлистов) переводу не подлежат, если не совпадают
 * дословно со встроенными названиями («Избранное», «Радио», «Закладки»).
 */
